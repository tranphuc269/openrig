// Factory Studio — turns a team definition into OpenRig spec files.
//
// Output layout (relative to the team folder):
//   factory.json                         person-facing source of truth
//   rig.yaml                             RigSpec, one pod "team"
//   CULTURE.md                           team culture: deliverable-first
//   agents/<member>/agent.yaml           AgentSpec importing the shared builtins
//   agents/<member>/guidance/role.md     role + place in the workflow
//   agents/<member>/guidance/deliverables.md   the documents to produce
//   agents/<member>/skills/<id>/...      copied library skills + custom skills

import { stringify } from "yaml";
import { deriveCanonicalSessionName } from "../session-name.js";
import { shellQuote } from "../../adapters/shell-quote.js";
import { deliverableFormat, type FactoryDeliverable, type FactoryMember, type FactoryTeam } from "./team.js";

export const FACTORY_POD_ID = "team";

/** How one selected library skill reaches the generated AgentSpec. */
export type SkillPlacement =
  /** Declared by the imported shared AgentSpec: reference by id. */
  | { kind: "shared"; id: string }
  /** Copied into agents/<member>/skills/<id>/ from an absolute folder. */
  | { kind: "copy"; id: string; sourceDir: string };

export type GeneratedFile =
  | { kind: "text"; content: string }
  | { kind: "copyDir"; sourceDir: string };

export interface GenerateOptions {
  /** Absolute path of the daemon's shared AgentSpec (specs/agents/shared). */
  sharedAgentDir: string;
  /** Resource ids the shared AgentSpec declares, per category. */
  sharedSkillIds: ReadonlySet<string>;
  /** Resolve a library skill id; null when it no longer exists. */
  resolveSkill: (libraryId: string, sharedSkillIds: ReadonlySet<string>) => SkillPlacement | null;
  /** The office tool agents use for Word/Excel documents. Without it, such documents can't be declared. */
  office?: OfficeToolOptions;
}

export interface OfficeToolOptions {
  /** Shell command that runs the office tool on agents' PATH: `rig office`. */
  command: string;
  /** Form library id → absolute path, format and display name; null when it was deleted. */
  resolveTemplate: (id: string) => { path: string; format: "docx" | "xlsx"; name: string } | null;
}

export interface GenerateResult {
  files: Map<string, GeneratedFile>;
  errors: string[];
}

const SHARED_PLUGINS = ["shared:openrig-core"];
const SHARED_RUNTIME_RESOURCES = [
  "shared:claude-default-settings",
  "shared:claude-default-mcp",
  "shared:codex-default-config",
  "shared:claude-activity-hooks",
];

export function sessionFor(team: Pick<FactoryTeam, "name">, member: Pick<FactoryMember, "id">): string {
  return deriveCanonicalSessionName(FACTORY_POD_ID, member.id, team.name);
}

function yamlDoc(header: string, value: unknown): string {
  return `# ${header}\n# Generated by Factory Studio — edit the team in the Studio, not this file.\n${stringify(value, { lineWidth: 0 })}`;
}

function rigYaml(team: FactoryTeam): string {
  const members = team.members.map((m) => ({
    id: m.id,
    label: m.title,
    agent_ref: `local:agents/${m.id}`,
    runtime: m.runtime,
    ...(m.model ? { model: m.model } : {}),
    ...(m.effort ? { effort: m.effort } : {}),
    role: m.role,
    profile: "default",
    cwd: ".",
  }));
  const edges = team.workflow === "sequential"
    ? team.members.slice(0, -1).map((m, i) => ({ kind: "delegates_to", from: m.id, to: team.members[i + 1]!.id }))
    : [];
  return yamlDoc(`Factory Studio team: ${team.title}`, {
    version: "0.2",
    name: team.name,
    summary: team.summary || team.title,
    culture_file: "CULTURE.md",
    // Full auto: Claude runs with --dangerously-skip-permissions and its one-time bypass warning is accepted.
    ...(team.autonomy === "full" ? { permission_policy: "builtin:yolo", non_interruptive: true } : {}),
    pods: [{ id: FACTORY_POD_ID, label: team.title, members, edges }],
    edges: [],
  });
}

function teamUsesOffice(team: FactoryTeam): boolean {
  return team.members.some((m) => m.deliverables.some((d) => {
    const f = deliverableFormat(d.path);
    return f === "docx" || f === "xlsx";
  }));
}

function cultureMd(team: FactoryTeam, office?: OfficeToolOptions): string {
  return [
    `# ${team.title} — team culture`,
    "",
    team.summary ? `${team.summary}\n` : "",
    "- Every member owns written deliverables. Work is done when the files exist at their declared paths",
    "  and meet their acceptance criteria — not when you say so in the chat.",
    "- Read the deliverables of the members before you; do not contradict them silently. If you disagree,",
    "  write the disagreement under an \"Open questions\" heading and tell the person.",
    "- Never invent facts the task did not give you. Mark assumptions as assumptions.",
    ...(team.autonomy === "full" ? [
      "- This team runs in full auto: the person is not watching. Never stop to wait for an answer or an approval.",
      "  When something is unclear, choose the most reasonable option, write it under an \"Assumptions\" heading in",
      "  your document, and keep going. Only `rig ask` the person when the task cannot be done at all without them.",
    ] : []),
    "- When the person asks for rework, change the same files and list what changed at the top under \"Revision notes\".",
    ...(office && teamUsesOffice(team) ? [
      "- Word (.docx) and Excel (.xlsx) documents are built and read with the office tool (skill `office-docs`).",
      `  Read a teammate's one with: \`${office.command} read <path>\``,
    ] : []),
    "",
  ].join("\n");
}

function draftBase(member: FactoryMember, d: FactoryDeliverable): string {
  return `.factory/drafts/${member.id}/${d.id}`;
}

function officeSteps(member: FactoryMember, d: FactoryDeliverable, office: OfficeToolOptions, form: { path: string; name: string } | null): string[] {
  const draft = draftBase(member, d);
  const style = form ? ` --style ${shellQuote(form.path)}` : "";
  const out: string[] = [];
  const docx = deliverableFormat(d.path) === "docx";
  out.push(
    docx
      ? "- **Format:** Word (.docx), built with the office tool (skill `office-docs`). Never write the .docx by hand and never just copy the form."
      : "- **Format:** Excel (.xlsx), built with the office tool (skill `office-docs`). Never write the .xlsx by hand and never just copy the form.",
  );
  if (form) {
    out.push(
      `- **Model to follow:** ${form.name} at \`${form.path}\`. Read it first and understand it: its sections${docx ? ", tables" : ", sheets, columns"} and level of detail.`,
      "  Then write YOUR document for this task in the same kind of structure. Adapt it: keep what fits, add sections or columns that help,",
      "  drop what doesn't apply, and improve on it where you can. Its sample or hint text is not content: replace all of it with real content.",
    );
  }
  out.push("", "How to build it:", "", "```bash");
  if (docx && form) {
    out.push(
      `${office.command} inspect ${shellQuote(form.path)}   # front-page <fields>, change-log table, the headings to follow`,
      `${office.command} read ${shellQuote(form.path)}      # what each section asks for (its [hints] and examples)`,
      `# 1. Write the BODY as Markdown in ${draft}.md, starting at the first heading. The cover, change log, sign-off page and`,
      "#    table of contents are kept from the model: don't repeat them. Don't type heading numbers (the model numbers headings).",
      `# 2. Fill the front pages in ${draft}.vars.json: {"Tên dự án": "…", "Ngày": ["…", "", ""], "row:<first change-log column>": [["…", …]]}`,
      `${office.command} docx${style} --content ${draft}.md --vars ${draft}.vars.json --out ${shellQuote(d.path)}`,
    );
  } else if (form) out.push(`${office.command} read ${shellQuote(form.path)}   # understand the model first`);
  if (docx && !form) {
    out.push(
      `# Write the whole document as Markdown in ${draft}.md: title, version/history table, every section with real content.`,
      `${office.command} docx --content ${draft}.md --out ${shellQuote(d.path)}`,
    );
  } else if (!docx) {
    out.push(
      `# Design the workbook in ${draft}.json as "sheets" (name, columns, rows), every row filled with real data for this task.`,
      `${office.command} xlsx${style} --data ${draft}.json --out ${shellQuote(d.path)}`,
    );
  }
  out.push(
    `${office.command} read ${shellQuote(d.path)}   # check it: real content everywhere, nothing left from the model's sample text`,
    "```",
    "",
    `To change it later, edit the draft and run the same \`${docx ? "docx" : "xlsx"}\` command again.`,
  );
  return out;
}

function deliverablesMd(member: FactoryMember, office: OfficeToolOptions | undefined, errors: string[]): string {
  if (member.deliverables.length === 0) {
    return "# Your deliverables\n\nNo documents are declared for you. Report your result as a message.\n";
  }
  const parts = ["# Your deliverables", "", "Write each document below at exactly the path shown, relative to your working directory.", ""];
  for (const d of member.deliverables) {
    const format = deliverableFormat(d.path);
    parts.push(`## ${d.title}`, "", `- **Path:** \`${d.path}\``, `- **Deliverable id:** \`${d.id}\``);
    if (d.acceptance) parts.push(`- **Done when:** ${d.acceptance}`);
    if (format === "docx" || format === "xlsx") {
      let form: { path: string; name: string } | null = null;
      if (d.template) {
        const resolved = office?.resolveTemplate(d.template) ?? null;
        if (!resolved) errors.push(`members.${member.id}.deliverables.${d.id}.template: the form "${d.template}" no longer exists; pick or upload it again`);
        else if (resolved.format !== format) errors.push(`members.${member.id}.deliverables.${d.id}.template: ${resolved.name} is a .${resolved.format} form but the document is .${format}`);
        else form = resolved;
      }
      if (office) parts.push(...officeSteps(member, d, office, form));
      else errors.push(`members.${member.id}.deliverables.${d.id}.path: Word and Excel documents need the office tool, which isn't available`);
    }
    if (d.outline) {
      const label = format === "xlsx" ? "What goes in the workbook:" : format === "docx" ? "Content outline (the Markdown draft follows it):" : "Follow this outline:";
      parts.push("", label, "", "```markdown", d.outline, "```");
    }
    parts.push("");
  }
  return parts.join("\n");
}

/** The office-docs skill: how to build and read Word and Excel documents. */
export function officeSkillMd(command: string): string {
  return `---
name: office-docs
description: "Build Word (.docx) and Excel (.xlsx) documents that follow a form, and read teammates' Word/Excel files. Use for every .docx or .xlsx deliverable."
---

# Office documents

Word and Excel files are zip packages: never write or edit them by hand, and never hand in a copy of a form.
Use the office tool, \`${command}\` (\`${command} --help\` lists every option).

## A form or sample is a model, not a file to hand back

When your deliverable names a model (form/sample) file:

1. \`${command} read <model>\` prints it as Markdown. Understand it: which sections or sheets, which tables and columns,
   how detailed, what tone. Its example rows, hint lines ("(Mô tả …)", "[Nhập …]", "……") are NOT content.
2. Write your own document for the task in that kind of structure. Adapt freely: keep what fits, add what helps,
   drop what doesn't apply, improve where you can. Every section gets real content from the task and your teammates' documents.
3. Build it in the model's look with \`--style <model>\` (below), then \`${command} read <your file>\` and check it.

## Word (.docx)

Markdown: \`#\`/\`##\`/\`###\` headings, paragraphs, \`-\` and \`1.\` lists (indent two spaces to nest), pipe tables,
\`> quotes\`, code blocks, \`---\` rules, \`<!-- pagebreak -->\`, **bold**, *italic*, \`code\`, [links](https://…).

With a model:

\`\`\`bash
${command} inspect <model.docx>    # its front-page <fields>, front-page tables (change log) and body headings
${command} docx --style <model.docx> --content draft.md --vars vars.json --out <path.docx>
\`\`\`

- \`--style\` keeps the model's front pages (everything before its first heading: cover, change log, sign-off page,
  table of contents) and its look (heading, list and table styles, page setup, header, footer). Everything from its
  first heading on is replaced by your draft, so its hints and examples never reach your document.
- So the draft is the BODY only: start at the first heading (\`# GIỚI THIỆU\`), never repeat the cover, change log,
  sign-off page or table of contents. Don't type heading numbers: when the model numbers headings, typed numbers are dropped.
- vars.json fills the front pages. A \`<Field>\` placeholder's key is the text inside the brackets:
  \`{"Tên dự án": "Hệ thống E-learning", "Mã hiệu tài liệu": "ELN-PTYC-01"}\`. A list fills repeated fields in order:
  \`{"Chức danh": ["Product Analyst", "Trưởng nhóm BA", "Trưởng dự án"], "Ngày": ["23/11/2026", "", ""]}\` ("" leaves one blank).
  \`"row:<first header cell>": [[…], […]]\` writes rows into that front-page table, e.g. the change log.
- The build report lists fields still empty; fill them or set them to "" on purpose. Word refreshes the table of
  contents when the file is opened.

Without a model, leave out \`--style\` and \`--vars\`, and write the whole document (title, history table, sections).
Only when a form was made with \`{{placeholders}}\` and must be filled in place: \`--template <form.docx> --vars vars.json\`.

## Excel (.xlsx)

Design the workbook as JSON, one entry per sheet, every row filled in:

\`\`\`json
{ "sheets": [
    { "name": "Test cases", "columns": ["ID", "Requirement", "Title", "Steps", "Expected result", "Priority"],
      "rows": [["TC-01", "REQ-01", "Log in", "1. Open the app\\n2. Enter email and password", "The home page opens", "High"]] },
    { "name": "Summary", "columns": ["Requirement", "Test cases"], "rows": [["REQ-01", 3]] } ] }
\`\`\`

\`\`\`bash
${command} xlsx --style <model.xlsx> --data data.json --out <path.xlsx>
\`\`\`

\`--style\` gives your sheets the model's header and cell look. Numbers stay numbers (42, not "42"); a string starting
with \`=\` is a formula; \`\\n\` makes a line break in a cell. To fill a form in place instead: \`--template <form.xlsx>\`
with \`cells\` ("Sheet!B2": value) and \`tables\` ({ "sheet", "start": "A5", "rows" }).

## Keep drafts

Keep the Markdown/JSON you built from (your deliverables guidance names the paths). To change a document, edit the
draft and build again.
`;
}

function roleMd(team: FactoryTeam, member: FactoryMember): string {
  const index = team.members.findIndex((m) => m.id === member.id);
  const prev = team.workflow === "sequential" && index > 0 ? team.members[index - 1] : undefined;
  const next = team.workflow === "sequential" ? team.members[index + 1] : undefined;
  const roster = team.members
    .map((m, i) => {
      const docs = m.deliverables.map((d) => `\`${d.path}\``).join(", ") || "no documents";
      return `${i + 1}. **${m.title}** (\`${sessionFor(team, m)}\`) — ${docs}`;
    })
    .join("\n");

  const flow: string[] = [];
  if (team.workflow === "sequential") {
    flow.push(`The team works in order. You are step ${index + 1} of ${team.members.length}.`);
    if (prev) {
      flow.push(`Wait until **${prev.title}** tells you their deliverables are ready, then read them before you start.`);
    } else {
      flow.push("You receive the task first, from the person.");
    }
    if (next) {
      flow.push(
        `When all your deliverables are written, hand off to **${next.title}**:`,
        "",
        "```bash",
        `rig send ${sessionFor(team, next)} "<task summary>. My deliverables are ready: <paths>." --verify`,
        "```",
      );
    } else {
      flow.push("You are the last step. When your deliverables are written, tell the person the team's work is ready for review.");
    }
  } else {
    flow.push("Members work in parallel on the same task. Read the other members' deliverables when they exist, and keep yours consistent with them.");
  }

  return [
    `# Role: ${member.title}`,
    "",
    `You are a member of the **${team.title}** team (OpenRig rig \`${team.name}\`).`,
    "",
    "## What you do",
    "",
    member.instructions || `Act as the team's ${member.title}.`,
    "",
    "## Workflow",
    "",
    ...flow,
    "",
    "## Team",
    "",
    roster,
    "",
    "Your required documents are in your deliverables guidance. Finish every one of them before you report done.",
    "",
  ].join("\n");
}

function customSkillMd(skill: FactoryMember["customSkills"][number]): string {
  const description = skill.description.replace(/"/g, "'");
  return `---\nname: ${skill.name}\ndescription: "${description}"\n---\n\n${skill.content}\n`;
}

function agentYaml(team: FactoryTeam, member: FactoryMember, opts: GenerateOptions, errors: string[], files: Map<string, GeneratedFile>): string {
  const base = `agents/${member.id}`;
  const useSkills: string[] = [];
  const localSkills: Array<{ id: string; path: string }> = [];
  const localIds = new Set<string>();

  const addLocal = (id: string): string => {
    let unique = opts.sharedSkillIds.has(id) ? `local-${id}` : id;
    let n = 2;
    while (localIds.has(unique)) unique = `${id}-${n++}`;
    localIds.add(unique);
    localSkills.push({ id: unique, path: `skills/${unique}` });
    useSkills.push(unique);
    return unique;
  };

  for (const libraryId of member.skills) {
    const placement = opts.resolveSkill(libraryId, opts.sharedSkillIds);
    if (!placement) {
      errors.push(`members.${member.id}.skills: skill "${libraryId}" is not in the skill library`);
      continue;
    }
    if (placement.kind === "shared") {
      if (!useSkills.includes(placement.id)) useSkills.push(placement.id);
    } else {
      const id = addLocal(placement.id);
      files.set(`${base}/skills/${id}`, { kind: "copyDir", sourceDir: placement.sourceDir });
    }
  }
  for (const custom of member.customSkills) {
    const id = addLocal(custom.name);
    files.set(`${base}/skills/${id}/SKILL.md`, { kind: "text", content: customSkillMd(custom) });
  }
  if (opts.office && teamUsesOffice(team)) {
    const id = addLocal("office-docs");
    files.set(`${base}/skills/${id}/SKILL.md`, { kind: "text", content: officeSkillMd(opts.office.command) });
  }

  return yamlDoc(`Factory Studio member: ${member.title}`, {
    name: member.id,
    version: "1.0",
    description: `${member.title} — Factory Studio team ${team.name}`,
    defaults: { runtime: member.runtime },
    imports: [{ ref: `path:${opts.sharedAgentDir}` }],
    profiles: {
      default: {
        uses: {
          skills: useSkills,
          guidance: [],
          subagents: [],
          plugins: SHARED_PLUGINS,
          runtime_resources: SHARED_RUNTIME_RESOURCES,
        },
      },
    },
    resources: {
      ...(localSkills.length ? { skills: localSkills } : {}),
      guidance: [
        { id: "role", path: "guidance/role.md" },
        { id: "deliverables", path: "guidance/deliverables.md" },
      ],
    },
    startup: {
      files: [
        { path: "guidance/role.md", orientation: "role", delivery_hint: "send_text", required: true },
        { path: "guidance/deliverables.md", delivery_hint: "send_text", required: true },
      ],
      actions: [],
    },
  });
}

export function generateTeamFiles(team: FactoryTeam, opts: GenerateOptions): GenerateResult {
  const files = new Map<string, GeneratedFile>();
  const errors: string[] = [];
  files.set("factory.json", { kind: "text", content: `${JSON.stringify(team, null, 2)}\n` });
  files.set("rig.yaml", { kind: "text", content: rigYaml(team) });
  files.set("CULTURE.md", { kind: "text", content: cultureMd(team, opts.office) });
  for (const member of team.members) {
    const base = `agents/${member.id}`;
    files.set(`${base}/guidance/role.md`, { kind: "text", content: roleMd(team, member) });
    files.set(`${base}/guidance/deliverables.md`, { kind: "text", content: deliverablesMd(member, opts.office, errors) });
    files.set(`${base}/agent.yaml`, { kind: "text", content: agentYaml(team, member, opts, errors, files) });
  }
  return { files, errors };
}
